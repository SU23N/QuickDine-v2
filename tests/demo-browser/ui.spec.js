import {test,expect} from '@playwright/test';
test('customer filters and mobile order shortcut keep the cart usable',async({page},info)=>{
 await page.setViewportSize({width:375,height:812});
 await page.goto('/#/r/yash-bagbahara/customer?table=7');
 await expect(page.locator('.menu-card')).toHaveCount(8);
 await page.getByRole('textbox',{name:'Search dishes…'}).fill('chicken');
 await expect(page.locator('.menu-card')).toHaveCount(1);
 await page.getByRole('checkbox',{name:'Veg only'}).check();
 await expect(page.locator('.menu-card')).toHaveCount(0);
 await page.getByRole('button',{name:'Reset filters',exact:true}).click();
 await page.getByRole('button',{name:'Breads',exact:true}).click();
 await page.getByRole('button',{name:'Add +',exact:true}).click();
 await page.getByRole('button',{name:'View order',exact:true}).click();
 await expect(page.locator('.checkout-panel')).toBeFocused();
 await expect(page.getByRole('button',{name:'View order',exact:true})).toBeHidden();
 await expect(page.locator('.checkout-total')).toContainText('₹45.00');
 await page.getByRole('button',{name:'Add one Butter Naan',exact:true}).click();
 await expect(page.locator('.checkout-total')).toContainText('₹90.00');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.evaluate(()=>window.scrollTo({top:0,left:0,behavior:"instant"}));
 await page.screenshot({path:info.outputPath('customer-mobile-checkout.png'),fullPage:true});
 await page.setViewportSize({width:1440,height:1000});
 await page.getByRole('button',{name:'All',exact:true}).click();
 await page.evaluate(()=>window.scrollTo({top:0,left:0,behavior:"instant"}));
 await page.screenshot({path:info.outputPath('customer-menu-desktop.png'),fullPage:true});
});
test('menu editor filters and availability changes stay scoped to the restaurant',async({page},info)=>{
 await page.goto('/#/r/yash-bagbahara/admin');
 await page.getByRole('textbox',{name:'Search menu editor'}).fill('paneer');
 const dish=page.locator('.menu-editor-card');
 await expect(dish).toHaveCount(1);
 await dish.getByRole('button',{name:'Available',exact:true}).click();
 await page.getByRole('combobox',{name:'Filter menu availability'}).selectOption('unavailable');
 await expect(dish).toHaveCount(1);
 await expect(dish.getByRole('button',{name:'Unavailable',exact:true})).toHaveAttribute('aria-pressed','false');
 await page.getByRole('textbox',{name:'Search menu editor'}).fill('');
 await page.getByRole('combobox',{name:'Filter menu availability'}).selectOption('all');
 await page.evaluate(()=>window.scrollTo({top:0,left:0,behavior:"instant"}));
 await page.screenshot({path:info.outputPath('menu-editor-desktop.png'),fullPage:true});
 await page.goto('/#/r/yash-bagbahara/customer?table=7');
 await expect(page.locator('.menu-card').filter({has:page.getByRole('heading',{name:'Paneer Butter Masala',exact:true})}).getByRole('button',{name:'Unavailable',exact:true})).toBeDisabled();
 await page.goto('/#/r/chhattisgarh-family-dhaba/customer?table=7');
 await expect(page.locator('.menu-card').filter({has:page.getByRole('heading',{name:'Paneer Butter Masala',exact:true})}).getByRole('button',{name:'Add +',exact:true})).toBeEnabled();
});
test('waiter view completes ready orders and cannot perform kitchen actions',async({page},info)=>{
 await page.goto('/#/r/yash-bagbahara/customer?table=7');
 await page.getByRole('button',{name:'Add +',exact:true}).first().click();
 await page.getByRole('button',{name:'Place demo order',exact:true}).click();
 await page.goto('/#/r/yash-bagbahara/waiter');
 await expect(page.locator('.queue-filters button.active')).toContainText('Ready');
 await page.getByRole('button',{name:'All active',exact:false}).click();
 await expect(page.locator('.demo-order-card')).toContainText('Table 7');
 await expect(page.getByRole('button',{name:'Accept order',exact:true})).toHaveCount(0);
 await expect(page.getByRole('button',{name:'Mark ready',exact:true})).toHaveCount(0);
 await page.goto('/#/r/yash-bagbahara/kitchen');
 await page.getByRole('button',{name:'Accept order',exact:true}).click();
 await page.evaluate(()=>window.scrollTo({top:0,left:0,behavior:"instant"}));
 await page.screenshot({path:info.outputPath('kitchen-preparing.png'),fullPage:true});
 await page.getByRole('button',{name:'Mark ready',exact:true}).click();
 await page.goto('/#/r/yash-bagbahara/waiter');
 await expect(page.locator('.queue-filters button.active')).toContainText('Ready');
 await expect(page.locator('.demo-order-card .state-badge')).toHaveText('ready');
 await page.evaluate(()=>window.scrollTo({top:0,left:0,behavior:"instant"}));
 await page.screenshot({path:info.outputPath('waiter-ready.png'),fullPage:true});
 await page.getByRole('button',{name:'Mark served / collected',exact:true}).click();
 await expect(page.locator('.demo-order-card')).toHaveCount(0);
 await page.getByRole('button',{name:'Completed',exact:false}).click();
 await expect(page.locator('.demo-order-card .state-badge')).toHaveText('completed');
});
