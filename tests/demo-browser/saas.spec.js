import {test,expect} from '@playwright/test';
test('demo onboarding creates a separate restaurant; owners can update branding and add a menu',async({page},info)=>{
 await page.goto('/#/console');
 await expect(page.getByText('DEMO WORKSPACE',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'+ Add restaurant',exact:true}).click();
 const dialog=page.getByRole('dialog');
 await dialog.getByLabel('Restaurant name',{exact:true}).fill('Test Family Dhaba');
 await dialog.getByLabel('Restaurant ID / URL slug').fill('test-family-dhaba');
 await dialog.getByLabel('Owner email').fill('owner@example.test');
 await dialog.getByRole('button',{name:'Create demo restaurant',exact:true}).click();
 await expect(dialog).toHaveCount(0);
 await expect(page.locator('.saas-table')).toContainText('Test Family Dhaba');
 await page.goto('/#/r/test-family-dhaba/owner');
 await expect(page.getByRole('heading',{name:'Test Family Dhaba',exact:true})).toBeVisible();
 await page.goto('/#/r/test-family-dhaba/admin');
 await page.getByRole('button',{name:'+ Add dish',exact:true}).click();
 await page.getByRole('dialog').getByLabel('Dish name',{exact:true}).fill('Test Paneer');
 await page.getByRole('dialog').getByLabel('Price in ₹').fill('250');
 await page.getByRole('dialog').getByRole('button',{name:'Save demo dish',exact:true}).click();
 await expect(page.locator('.compact-list')).toContainText('Test Paneer');
 await page.goto('/#/r/yash-bagbahara/admin');
 await expect(page.locator('.compact-list')).not.toContainText('Test Paneer');
 await page.goto('/#/r/test-family-dhaba/settings');
 await page.getByLabel('Restaurant name',{exact:true}).fill('Updated Family Dhaba');
 await page.getByRole('button',{name:'Save demo branding',exact:true}).click();
 await expect(page.locator('.workspace-pill')).toContainText('Updated Family Dhaba');
 await page.screenshot({path:info.outputPath('restaurant-branding.png'),fullPage:true});
});
test('a table order reaches its own kitchen, persists after refresh and updates owner recorded sales',async({page},info)=>{
 await page.goto('/#/r/yash-bagbahara/customer?table=7');
 await page.getByRole('button',{name:'Add +',exact:true}).first().click();
 await page.getByRole('button',{name:'Place demo order',exact:true}).click();
 await expect(page.locator('.saas-success')).toContainText('Demo order saved');
 await page.goto('/#/r/yash-bagbahara/kitchen');
 await expect(page.locator('.demo-order-card')).toContainText('Table 7');
 await page.getByRole('button',{name:'Accept order',exact:true}).click();
 await page.getByRole('button',{name:'Mark ready',exact:true}).click();
 await page.reload();
 await expect(page.locator('.demo-order-card .state-badge')).toHaveText('ready');
 await page.goto('/#/r/chhattisgarh-family-dhaba/kitchen');
 await expect(page.locator('.demo-order-card')).toHaveCount(0);
 await page.goto('/#/r/yash-bagbahara/owner');
 await page.getByRole('button',{name:'Complete service',exact:true}).click();
 await page.getByRole('button',{name:'Record food payment',exact:true}).click();
 await expect(page.locator('.saas-metric').first()).toContainText('₹220.00');
 await page.screenshot({path:info.outputPath('owner-workspace.png'),fullPage:true});
});
test('subscription invoices renew on a recorded demo payment and mobile console does not overflow',async({page},info)=>{
 await page.goto('/#/r/yash-bagbahara/billing');
 await page.locator('.plan-card').filter({hasText:'Growth · sample'}).getByRole('button',{name:'Create demo invoice',exact:true}).click();
 await page.goto('/#/console?tab=billing');
 await page.getByRole('button',{name:'Record demo payment',exact:true}).click();
 await page.getByRole('dialog').getByLabel('Demo receipt reference').fill('demo-reference-1');
 await page.getByRole('dialog').getByRole('button',{name:'Record demo payment',exact:true}).click();
 await expect(page.locator('.saas-table .state-badge')).toHaveText('paid');
 await page.goto('/#/r/yash-bagbahara/billing');
 await expect(page.locator('.saas-callout')).toContainText('Growth · sample');
 await expect(page.locator('.saas-callout .state-badge')).toHaveText('active');
 await page.setViewportSize({width:375,height:812});
 await page.goto('/#/console');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
 await page.screenshot({path:info.outputPath('mobile-console.png'),fullPage:true});
});
