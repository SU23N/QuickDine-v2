export function useLanguageState() {
  const [lang, set] = useState(() => {
    try {
      return localStorage.getItem("quickdine-language") === "hi" ? "hi" : "en";
    } catch {
      return "en";
    }
  });
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  return {
    lang,
    setLang: (value) => {
      set(value);
      try {
        localStorage.setItem("quickdine-language", value);
      } catch {}
    },
    t: (key) => dictionary[lang][key] || key,
  };
}
export const useLanguage = () => useContext(LanguageContext);
export const label = (item, field, lang) =>
  lang === "hi" && item[`${field}Hi`] ? item[`${field}Hi`] : item[field];
export const money = (paise) =>
  new Intl.NumberFormat("en-IN", {
    style: "currency",
    currency: "INR",
    maximumFractionDigits: 2,
  }).format((paise || 0) / 100);

export function formatTime(timestamp, lang = "en") {
  return timestamp?.toDate().toLocaleString(lang === "hi" ? "hi-IN" : "en-IN", {
    timeZone: "Asia/Kolkata",
  });
}
